package io.quarkiverse.almanac.cli;

import io.quarkiverse.almanac.dataset.Dataset;
import io.quarkiverse.almanac.dataset.Kind;
import io.quarkiverse.almanac.maven.QuarkusVersion;
import io.quarkiverse.almanac.util.Log;
import io.quarkiverse.almanac.util.SnapshotStore;
import picocli.CommandLine.Command;
import picocli.CommandLine.Mixin;
import picocli.CommandLine.Model.CommandSpec;
import picocli.CommandLine.Option;
import picocli.CommandLine.Spec;

import java.io.IOException;
import java.io.PrintWriter;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import java.util.concurrent.Callable;

/// `platform`: writes `platform-bom.json` snapshots, of the platform BOM of the same version, for the releases the
/// committed dataset does not have them for yet.
@Command(name = "platform", description = "Write platform-bom.json snapshots: the platform BOM "
        + "io.quarkus.platform:quarkus-bom, which applications generated by code.quarkus.io import, of the releases "
        + "that have a platform release of the same version (as its maven-metadata.xml lists them) and that the "
        + "dataset does not have it for yet. The dataset keeps how the platform BOM differs from the release's BOM, so "
        + "a release needs its bom.json snapshot (work folder or dataset) first; the others are left out. Resolved as "
        + "the bom command resolves a BOM.")
public final class PlatformCommand implements Callable<Integer> {

    @Mixin
    CommonOptions common;

    @Spec
    CommandSpec spec;

    @Option(names = "--versions", defaultValue = "all", paramLabel = "all|streams|LIST",
            description = "Releases to process (default: ${DEFAULT-VALUE}).")
    String versions;

    @Option(names = "--force", description = "Also process releases the dataset has, and rewrite existing snapshots.")
    boolean force;

    @Option(names = "--missing", description = "Print the releases that would be processed, one a line, instead of "
            + "processing them: no pom is downloaded, only the maven-metadata.xml of the BOM and of the platform BOM "
            + "are read.")
    boolean missing;

    @Override
    public Integer call() throws IOException {
        try (Workspace workspace = Workspace.open(common)) {
            List<QuarkusVersion> todo = toProcess(workspace, workspace.select(versions), force);
            if (missing) {
                PrintWriter out = spec.commandLine().getOut();
                todo.forEach(version -> out.println(version.text()));
                out.flush();
                return 0;
            }
            return writeSnapshots(workspace, todo, force) ? 0 : 1;
        }
    }

    /// The releases among `versions` that have a platform release of the same version, that the dataset has no
    /// platform BOM of (with `force`, also those it has) and that have a BOM snapshot (work folder or dataset), logging
    /// how many are left out and why. Offline without a cached `maven-metadata.xml` of the platform BOM, the releases
    /// with a platform BOM snapshot (work folder or dataset) stand for the published ones.
    ///
    /// @throws IOException when the platform BOM's `maven-metadata.xml` cannot be read online
    static List<QuarkusVersion> toProcess(Workspace workspace, List<QuarkusVersion> versions, boolean force)
            throws IOException {
        SnapshotStore snapshots = workspace.snapshots();
        Set<String> published;
        boolean listed = true;
        try {
            published = new HashSet<>(workspace.platformBoms().published());
        } catch (IOException e) {
            if (!workspace.repo().http().offline()) {
                throw e;
            }
            published = new HashSet<>(snapshots.versionsWith(SnapshotStore.PLATFORM_BOM));
            listed = false;
            Log.info("platform: the platform BOM's maven-metadata.xml is not available offline (%s); using the %d "
                    + "platform BOM snapshots of the work folder and the dataset", e.getMessage(), published.size());
        }
        Dataset dataset = workspace.dataset();
        List<QuarkusVersion> todo = new ArrayList<>();
        List<String> unpublished = new ArrayList<>();
        List<String> withoutBom = new ArrayList<>();
        int known = 0;
        for (QuarkusVersion version : versions) {
            String v = version.text();
            if (!published.contains(v)) {
                unpublished.add(v);
            } else if (!force && dataset.has(v, Kind.PLATFORM)) {
                known++;
            } else if (!snapshots.exists(v, SnapshotStore.BOM)) {
                withoutBom.add(v);
            } else {
                todo.add(version);
            }
        }
        if (!unpublished.isEmpty()) {
            Log.info("platform: %d of %d selected releases have no platform %s of the same version (%s)",
                    unpublished.size(), versions.size(), listed ? "release" : "BOM known offline",
                    abbreviated(unpublished));
        }
        if (known > 0) {
            Log.info("platform: %d releases already in the dataset (--force processes them again)", known);
        }
        if (!withoutBom.isEmpty()) {
            Log.warn("platform: %d releases left out, without a BOM snapshot to keep their platform BOM's differences "
                    + "from (%s)", withoutBom.size(), abbreviated(withoutBom));
        }
        return todo;
    }

    /// Writes the platform BOM snapshots of the given releases in parallel, until requests stop; false when any release
    /// failed or was not attempted.
    static boolean writeSnapshots(Workspace workspace, List<QuarkusVersion> versions, boolean force)
            throws IOException {
        return BomCommand.writeSnapshots(workspace, workspace.platformBoms(), versions, force);
    }

    /// The first five, then `...` when there are more.
    private static String abbreviated(List<String> versions) {
        return String.join(", ", versions.subList(0, Math.min(5, versions.size())))
                + (versions.size() > 5 ? ", ..." : "");
    }
}
